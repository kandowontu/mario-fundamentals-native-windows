void YachtGame::finishComputerTurn(int preferredCategory) {
    const int bestCategory = preferredCategory >= 0
        ? preferredCategory : yachtComputerCategory(dice_, computerScores_);
    if (bestCategory < 0) return;
    pendingComputerScoreCategory_ = bestCategory;
    computerScoreDelaySourceTicks_ = 0;
    showComputerDice_ = true;
    // CODE 18 alternates the two source lead-ins before speaking the line.
    host_.play((++computerAnnouncementCount_ & 1) ? 11432 : 11435,
               kMacYachtHostAnchor.x, kMacYachtHostAnchor.y);
    if (const int movie = categoryMovie(bestCategory); movie >= 0) host_.queue(movie);
    status_ = L"Mario puts " + std::to_wstring(yachtCategoryScore(bestCategory, dice_)) + L" on the " +
              std::wstring(categoryName(bestCategory)) + L" line. Your roll.";
    computerRerollStage_ = 3;
}

void YachtGame::advanceRound() {
    ++round_;
    if (round_ < 12) return;
    const int human = total(humanScores_); const int computer = total(computerScores_);
    winner_ = human == computer ? 2 : (human > computer ? 1 : -1);
    status_ = winner_ == 2 ? L"It's a tie!" : winner_ > 0 ? L"Congratulations! You win!" :
                                                      L"Looks like Mario wins this time!";
}

void YachtGame::beginOutcome() {
    if (!winner_ || outcomePhase_ != OutcomePhase::None) return;
    outcomeVisibleDiceCount_ = 0;
    int movie = 0;
    if (winner_ == 2) movie = 11442;                         // CODE 18 index 42
    else if (winner_ > 0)
        movie = context_.random.below(2000) / 1000 ? 11445 : 11444;
    else movie = context_.random.below(2000) / 1000 ? 11443 : 11439;
    if (host_.active()) host_.queue(movie);
    else host_.play(movie, kMacYachtHostAnchor.x, kMacYachtHostAnchor.y);
    outcomePhase_ = OutcomePhase::Announcement;
}

bool YachtGame::finished() const {
    return outcomePhase_ == OutcomePhase::Complete;
}

bool YachtGame::tickOutcome() {
    if (outcomePhase_ == OutcomePhase::None || outcomePhase_ == OutcomePhase::Complete) {
        return false;
    }
    switch (outcomePhase_) {
    case OutcomePhase::Announcement:
        if (host_.active()) return false;
        if (winner_ > 0 && winner_ != 2) {
            context_.audio.playMusic(audio_catalog::playerWinMusic(dosEdition(), 4));
            showComputerDice_ = true;
            held_.fill(false);
            outcomeVisibleDiceCount_ = 0;
            outcomePhase_ = OutcomePhase::VictoryDice;
        } else {
            outcomeDelayTicks_ = 9;
            outcomePhase_ = OutcomePhase::PreReplayDelay;
        }
        return true;
    case OutcomePhase::VictoryDice:
        // $1B16 creates one white die per controller pass. The fifth pass
        // immediately starts the player-only celebration movie 6022.
        if (outcomeVisibleDiceCount_ < static_cast<int>(dice_.size())) {
            const std::size_t index = static_cast<std::size_t>(outcomeVisibleDiceCount_);
            dice_[index] = outcomeVisibleDiceCount_ + 1;
            ++outcomeVisibleDiceCount_;
        }
        if (outcomeVisibleDiceCount_ >= static_cast<int>(dice_.size())) {
            outcomeAnimation_.play(6022, 69, 69);
            outcomePhase_ = OutcomePhase::Celebration;
        }
        return true;
    case OutcomePhase::Celebration:
        if (outcomeAnimation_.active()) return false;
        outcomeDelayTicks_ = 2;
        outcomePhase_ = OutcomePhase::PreReplayDelay;
        return true;
    case OutcomePhase::PreReplayDelay:
        if (outcomeDelayTicks_-- > 0) return true;
        // $1B8C uses index 53 for every result: the replay question.
        host_.play(11453, kMacYachtHostAnchor.x, kMacYachtHostAnchor.y);
        outcomePhase_ = OutcomePhase::ReplayPrompt;
        return true;
    case OutcomePhase::ReplayPrompt:
        if (host_.active()) return false;
        outcomeDelayTicks_ = 2;
        outcomePhase_ = OutcomePhase::PostReplayDelay;
        return true;
    case OutcomePhase::PostReplayDelay:
        if (outcomeDelayTicks_-- > 0) return true;
        outcomeClearTick_ = 0;
        outcomePhase_ = OutcomePhase::ScorecardClear;
        return true;
    case OutcomePhase::ScorecardClear:
        if (outcomeClearTick_ < 24) {
            const int category = outcomeClearTick_ / 2;
            humanScores_[category] = -1;
            computerScores_[category] = -1;
            if ((category & 1) == 0) context_.audio.playSound(5003);
            ++outcomeClearTick_;
            return true;
        }
        outcomeDelayTicks_ = 9;
        outcomePhase_ = OutcomePhase::FinishDelay;
        return true;
    case OutcomePhase::FinishDelay:
        if (outcomeDelayTicks_-- > 0) return true;
        outcomePhase_ = OutcomePhase::Complete;
        return true;
    case OutcomePhase::None:
    case OutcomePhase::Complete:
        return false;
    }
    return false;
}

