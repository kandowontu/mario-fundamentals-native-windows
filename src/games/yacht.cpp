int yachtScoreCategoryAt(Point point) {
    if (point.x < kPlayerScoreLineLeft ||
        point.x >= kPlayerScoreLineLeft + kPlayerScoreLineWidth ||
        point.y < kPlayerScoreLineTop ||
        point.y >= kPlayerScoreLineTop + kPlayerScoreLineHeight * kScoreLineCount) {
        return -1;
    }
    const int sourceRow = (point.y - kPlayerScoreLineTop) / kPlayerScoreLineHeight;
    return 11 - sourceRow;
}

Rect yachtDieRect(int index, bool held) {
    if (index < 0 || index >= static_cast<int>(kDieLefts.size())) return {};
    const int left = kDieLefts[static_cast<std::size_t>(index)];
    const int top = held ? kHeldDieTop : kRerollDieTop;
    return {left, top, left + kDieWidth, top + kDieHeight};
}

int yachtRemainingRollMarkers(int completedRolls, bool rollPending) {
    return std::clamp(3 - completedRolls - (rollPending ? 1 : 0), 0, 3);
}

bool yachtComputerRerollSpeechEligible(int rollsRemaining,
                                       const std::array<bool, 5>& held) {
    // CODE 18 $16E2 requires rolls remaining, an adviser reroll, and $227C > 1.
    // $227C counts flag-zero white dice, including the all-five-white case.
    return rollsRemaining > 0 && std::count(held.begin(), held.end(), false) > 1;
}

bool yachtHasWhiteDieToReroll(const std::array<bool, 5>& held) {
    return std::any_of(held.begin(), held.end(), [](bool heldDie) { return !heldDie; });
}

YachtGame::YachtGame(GameContext context)
    : Game(context), host_(context.assets, context.graphics, context.audio, true,
          [](int resourceId, Point scaled) {
              if (resourceId >= 10000) return Point{118, 1};
              return scaled;
          }),
      rollAnimation_(context.assets, context.graphics, context.audio),
      gestureAnimation_(context.assets, context.graphics, context.audio, true,
          [](int resourceId, Point scaled) {
              if (resourceId == 6021) return Point{-258, -90};
              return scaled;
          }),
      idleActorMovie_(context.assets, 6021),
      outcomeAnimation_(context.assets, context.graphics, context.audio) {
    // CODE 18 $318C initializes the four-joke cursor once when the Yacht
    // module is loaded.  $142E increments it before every joke.
    idleJokeIndex_ = context_.random.below(4000) / 1000;
    reset();
}

