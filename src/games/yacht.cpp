bool sourcePraiseEligible(int category, int score) {
    // CODE 18 $1E5A receives the scorecard's top-to-bottom category index.
    // Convert the native Aces..Yacht order to Yacht..Aces before applying
    // its literal category-specific thresholds.
    const int sourceCategory = 11 - category;
    switch (sourceCategory) {
    case 0: return score == 50;  // Yacht
    case 1: return score == 30;  // Big straight
    case 2: return score == 25;  // Little straight
    case 3:
    case 4: return score > 0;    // Four of a kind / full house
    case 5: return score > 20;   // Choice
    case 6: return score > 12;   // Sixes
    case 7: return score > 10;   // Fives
    case 8: return score > 8;    // Fours
    case 9: return score > 6;    // Threes
    case 10: return score > 4;   // Deuces
    case 11: return score > 2;   // Aces
    default: return false;
    }
}

