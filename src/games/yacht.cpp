int YachtGame::categoryMovie(int category) {
    // CODE 18 stores the spoken score-line names in descending display order:
    // Big Straight through Aces use 11400..11410. Yacht uses its separate
    // source clip (sound 6006) at movie 11470.
    if (category == 11) return 11470;
    if (category < 0 || category > 10) return -1;
    return 11410 - category;
}

