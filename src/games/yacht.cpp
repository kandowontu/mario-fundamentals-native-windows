std::array<bool, 5> yachtComputerRerolls(const std::array<int, 5>& dice,
                                         const std::array<int, 12>& scores) {
    std::array<bool, 5> reroll{};
    if (sourceReadyCategory(dice, scores) >= 0) return reroll;

    const auto counts = yachtCounts(dice);
    const auto adviserScores = sourceAdviserScores(dice);
    const int triple = sourceTripleValue(counts);
    if (triple > 0 && (sourceCategoryOpen(10, scores) || sourceCategoryOpen(6, scores) ||
                       sourceCategoryOpen(triple - 1, scores) || sourceCategoryOpen(7, scores))) {
        sourceKeepOnly(reroll, dice, triple);
        return reroll;
    }

    int straightFirst = 0;
    const int straightLength = sourceLongestRun(dice, counts, &straightFirst);
    const int straightCategory = sourceCategoryOpen(9, scores) ? 9 :
                                 sourceCategoryOpen(8, scores) ? 8 : -1;
    if (straightLength >= 3 && straightCategory >= 0) {
        int special = -1;
        if (straightCategory == 9 && straightFirst == 1) special = 5;
        else if (straightCategory == 9 && straightFirst == 3) special = 2;
        bool specialKept = false;
        std::array<int, 7> keptCounts{};
        for (std::size_t index = 0; index < dice.size(); ++index) {
            const int value = dice[index];
            const bool inRun = value >= straightFirst &&
                               value < straightFirst + straightLength;
            const bool keepSpecial = !inRun && value == special && !specialKept;
            reroll[index] = !inRun && !keepSpecial;
            if (!reroll[index]) {
                ++keptCounts[value];
                specialKept |= keepSpecial;
            }
        }
        // `$3DB0` repeatedly removes the first member of every duplicate,
        // leaving the final source-order occurrence selected.
        for (int value = 1; value <= 6; ++value) {
            int remove = keptCounts[value] - 1;
            for (std::size_t index = 0; index < dice.size() && remove > 0; ++index) {
                if (!reroll[index] && dice[index] == value) {
                    reroll[index] = true;
                    --remove;
                }
            }
        }
        return reroll;
    }

    const auto pairs = sourcePairValues(counts);
    if (pairs[0] > 0 && pairs[1] > 0 && sourceCategoryOpen(7, scores)) {
        sourceKeepOnly(reroll, dice, pairs[0], pairs[1]);
        return reroll;
    }

    const int highestUpper = sourceHighestOpenUpperPresent(adviserScores, scores);
    for (const int pair : {pairs[1], pairs[0]}) {
        if (pair == 0) continue;
        if (sourceCategoryOpen(pair - 1, scores) || sourceCategoryOpen(7, scores) ||
            sourceCategoryOpen(6, scores)) {
            sourceKeepOnly(reroll, dice, pair);
            return reroll;
        }
        if (highestUpper >= 4) {
            sourceKeepOnly(reroll, dice, highestUpper);
            return reroll;
        }
        if (sourceCategoryOpen(10, scores)) {
            sourceKeepOnly(reroll, dice, pair);
            return reroll;
        }
    }

    if (highestUpper > 0) {
        sourceKeepOnly(reroll, dice, highestUpper);
        return reroll;
    }
    reroll.fill(true);
    return reroll;
}

std::array<bool, 5> yachtComputerHeldDice(const std::array<int, 5>& dice,
                                          const std::array<int, 12>& scores) {
    auto held = yachtComputerRerolls(dice, scores);
    for (bool& value : held) value = !value;
    return held;
}

int yachtComputerCategory(const std::array<int, 5>& dice,
                          const std::array<int, 12>& scores) {
    if (const int ready = sourceReadyCategory(dice, scores); ready >= 0) return ready;
    const auto counts = yachtCounts(dice);
    const auto adviserScores = sourceAdviserScores(dice);
    int firstOpen = -1;
    int lastPositive = -1;
    int bestSource = -1;
    int bestScore = -999;
    for (int sourceCategory = 0; sourceCategory < 12; ++sourceCategory) {
        if (!sourceCategoryOpen(sourceCategory, scores)) continue;
        if (firstOpen < 0) firstOpen = sourceCategory;
        if (adviserScores[sourceCategory] > bestScore) {
            bestScore = adviserScores[sourceCategory];
            bestSource = sourceCategory;
        }
        if (adviserScores[sourceCategory] > 0) lastPositive = sourceCategory;
    }
    if (firstOpen < 0) return -1;
    if (lastPositive < 0) lastPositive = firstOpen;

    // Four Kind through Yacht are accepted immediately. Upper lines and
    // Choice pass through CODE 18's triple/pair and low-line sacrifice rules.
    if (bestSource < 6 || bestSource == 11) {
        const int triple = sourceTripleValue(counts);
        if (triple > 0 && sourceCategoryOpen(triple - 1, scores)) {
            bestSource = triple - 1;
        } else if (bestSource < 6 || bestScore < 20) {
            int openPairUpper = -1;
            for (int sourceCategory = 0; sourceCategory < 6; ++sourceCategory) {
                if (counts[sourceCategory + 1] == 2 &&
                    sourceCategoryOpen(sourceCategory, scores)) {
                    openPairUpper = sourceCategory;
                    break;
                }
            }
            bestSource = openPairUpper >= 0 ? openPairUpper : lastPositive;
            if (bestSource >= 3 && firstOpen < 2) bestSource = firstOpen;
        }
    }
    return kSourceToNativeCategory[bestSource];
}

int YachtGame::total(const std::array<int, 12>& scores) const {
    int result = 0;
    for (int score : scores) if (score >= 0) result += score;
    return result;
}

void YachtGame::scoreHuman(int category) {
    if (rolls_ == 0 || category < 0 || category >= 12) return;
    if (humanScores_[category] >= 0) {
        // The already-filled-line path at $82C uses an equal index 13/14 draw.
        const int movie = context_.random.below(2000) / 1000 == 0 ? 11413 : 11414;
        status_ = sourceYachtMovieText(movie);
        host_.play(movie, kMacYachtHostAnchor.x, kMacYachtHostAnchor.y);
        return;
    }

    const int score = yachtCategoryScore(category, dice_);
    humanScores_[category] = score;
    context_.audio.playSound(5003);

    int movie = 11422;  // $1226: the source's low/zero-score "Okay!"
    if (category == 11 && score == 50) {
        movie = 11427;
    } else if (sourcePraiseEligible(category, score)) {
        if (total(humanScores_) > total(computerScores_)) {
            // $11EE first chooses between praise and Mario-frustration, then
            // $190 lazily shuffles the selected three-entry pool.
            if (context_.random.below(2000) / 1000 == 0) {
                movie = drawDialoguePool(positiveReactionPool_, positiveReactionPoolCursor_);
            } else {
                movie = drawDialoguePool(worriedReactionPool_, worriedReactionPoolCursor_);
            }
        } else {
            movie = drawDialoguePool(friendlyReactionPool_, friendlyReactionPoolCursor_);
        }
    }
    status_ = sourceYachtMovieText(movie);
    pendingComputerAfterSpeech_ = true;
    pendingScoreReactionMovie_ = movie;
}

